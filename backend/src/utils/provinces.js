// Exact province name from what a client sent (trimmed; capitals and accents must match), else null.
export const findProvince = (value) => {
    if (typeof value !== "string") {
        return null;
    }
    const name = value.trim();
    return PROVINCES.find((province) => province === name) ?? null;
};
